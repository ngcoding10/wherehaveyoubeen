// every landmark has its own sprite (keyed by landmark id); the classic ones above keep their names
for (const [k, v] of Object.entries(LANDMARK_SPRITES)) if (!SPRITES[k]) SPRITES[k] = v;

const cache = new Map();
/** Render sprite to a canvas with outline, scaled by `scale` (nearest-neighbour). */
export function renderSprite(key, scale = 4) {
  const ck = key + '@' + scale;
  if (cache.has(ck)) return cache.get(ck);
  const [base, swapName] = key.split('|');
  const swap = SWAPS[swapName] || {};
  const rows = normalize(SPRITES[base] || SPRITES.ruins).map(r => [...r].map(ch => swap[ch] || ch).join(''));
  const W = 18, H = 18;
  const grid = Array.from({ length: H }, () => Array(W).fill(null));
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
    const ch = rows[y][x];
    if (ch && ch !== '.') grid[y + 1][x + 1] = PALETTE[ch] || '#ff00ff';
  }
  const out = grid.map(r => r.slice());
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    if (grid[y][x]) continue;
    const n = [[1,0],[-1,0],[0,1],[0,-1]].some(([dx,dy]) => grid[y+dy]?.[x+dx]);
    if (n) out[y][x] = OUTLINE;
  }
  const c = document.createElement('canvas');
  c.width = W * scale; c.height = H * scale;
  const ctx = c.getContext('2d');
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    if (!out[y][x]) continue;
    ctx.fillStyle = out[y][x];
    ctx.fillRect(x * scale, y * scale, scale, scale);
  }
  cache.set(ck, c);
  return c;
}

export function normalize(rows) {
  let r = rows.map(s => s.padEnd(16, '.').slice(0, 16));
  while (r.length < 16) r.unshift('.'.repeat(16));
  // bottom-align: drop trailing blank rows then re-pad on top
  while (r.length && /^\.+$/.test(r[r.length - 1])) r.pop();
  while (r.length < 16) r.unshift('.'.repeat(16));
  return r.slice(-16);
}

export function spriteDataURL(key, scale = 4) {
  return renderSprite(key, scale).toDataURL();
}

